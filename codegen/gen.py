#!/usr/bin/env python3
# SPDX-License-Identifier: Apache-2.0
"""Generate code from opset/v1/opset.yaml (invariant I10).

Outputs:
  server/worker/reflop_worker/ops_generated.py   static op table (I2)
  client/python/reflop/_opset_generated.py       client name → id mapping
  docs/OPSET.md                                  human-readable table

    python codegen/gen.py           # write files
    python codegen/gen.py --check   # fail if any file is out of date (CI)

The server table references every PyTorch overload by a literal attribute
path written into the generated source. Nothing is looked up by a string
at run time.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OPSET = ROOT / "opset/v1/opset.yaml"
SERVER_OUT = ROOT / "server/worker/reflop_worker/ops_generated.py"
CLIENT_OUT = ROOT / "client/python/reflop/_opset_generated.py"
DOC_OUT = ROOT / "docs/OPSET.md"
GO_OUT = ROOT / "pkg/opset/table_generated.go"

FLAG_BITS = {"IDX": 1, "RNG": 2, "DDS": 4, "ALLOC": 8, "ENUM": 16, "UNINIT": 32, "FUNC": 64,
             "RESTRICTED": 128, "CLIENT": 256, "BANNED": 512}
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

HEADER = "# SPDX-License-Identifier: Apache-2.0\n# Generated by codegen/gen.py from opset/v1/opset.yaml. Do not edit.\n"


def load() -> dict:
    doc = yaml.safe_load(OPSET.read_text())
    ids, names = set(), set()
    for e in doc["ops"]:
        if e["id"] in ids or e["name"] in names:
            sys.exit(f"gen: duplicate id or name: {e['id']} {e['name']}")
        ids.add(e["id"])
        names.add(e["name"])
        for f in e.get("flags", []):
            if f not in FLAG_BITS:
                sys.exit(f"gen: unknown flag {f} on {e['name']}")
        for need in ("IDX", "ALLOC", "RESTRICTED", "DDS"):
            if need in e.get("flags", []) and "CLIENT" not in e.get("flags", []) and not e.get("validator") \
                    and not (need == "DDS"):
                sys.exit(f"gen: {e['name']} has {need} but no validator (§8.2)")
    return doc


def flag_value(flags: list[str]) -> int:
    v = 0
    for f in flags:
        v |= FLAG_BITS[f]
    return v


def arg_tuple(a: dict) -> str:
    has_default = "default" in a
    return (f"A({a['name']!r}, {a['type']!r}, {bool(a.get('kwarg_only'))!r}, "
            f"{has_default!r}, {a.get('default')!r})")


def op_ref(name: str) -> str:
    ns, base, ov = name.split(".", 2)
    for part in (base, ov):
        if not IDENT.match(part):
            sys.exit(f"gen: unsafe operator name {name}")
    if ns == "aten":
        return f"_r(lambda: _aten.{base}.{ov})"
    if ns == "reflop":
        return f"_n({base!r})"
    sys.exit(f"gen: unknown namespace in {name}")


def gen_server(doc: dict) -> str:
    out = [HEADER, '"""Static operator table. Dispatch is integer id → entry only (invariant I2)."""\n',
           "from __future__ import annotations\n",
           "import torch\n",
           "from .opspec import A, OpSpec\n",
           "_aten = torch.ops.aten\n",
           f"OPSET_VERSION = {doc['opset_version']}",
           f"PINNED_TORCH = {doc['pinned_torch']!r}\n",
           "FLAG_" + "\nFLAG_".join(f"{k} = {v}" for k, v in FLAG_BITS.items()) + "\n",
           "",
           "def _r(get):",
           "    # Overloads absent from this PyTorch build (e.g. the legacy runtime)",
           "    # are disabled, never looked up again.",
           "    try:",
           "        return get()",
           "    except (AttributeError, RuntimeError):",
           "        return None\n",
           "",
           "def _n(name):",
           "    # reflop-native implementations, bound in natives.py by literal name.",
           "    return ('native', name)\n",
           "",
           "OPS: dict[int, OpSpec] = {"]
    for e in doc["ops"]:
        s = e["schema"]
        args = ", ".join(arg_tuple(a) for a in s["args"])
        rets = ", ".join(repr(r["type"]) for r in s["returns"])
        enums = {k: list(v) for k, v in (e.get("enum_args") or {}).items()}
        out.append(
            f"    {e['id']}: OpSpec({e['id']}, {e['name']!r}, {op_ref(e['name'])}, ({args}{',' if len(s['args']) == 1 else ''}), "
            f"({rets}{',' if len(s['returns']) == 1 else ''}), {flag_value(e.get('flags', []))}, {e['tier']}, "
            f"{e.get('validator')!r}, {e.get('cost', 'elementwise')!r}, {e.get('capability')!r}, {enums!r}, "
            f"{tuple(e.get('devices', ['cuda', 'cpu']))!r}),")
    out.append("}\n")
    return "\n".join(out)


def gen_client(doc: dict) -> str:
    out = [HEADER, '"""Client view of opset v1: name → (id, flags, schema). Client-side only."""\n',
           f"OPSET_VERSION = {doc['opset_version']}",
           f"PINNED_TORCH = {doc['pinned_torch']!r}\n",
           "FLAG_" + "\nFLAG_".join(f"{k} = {v}" for k, v in FLAG_BITS.items()) + "\n",
           "# name: (id, flags, tier, args[(name, type, kwarg_only, has_default, default)], returns, enums, capability)",
           "OPS = {"]
    for e in doc["ops"]:
        s = e["schema"]
        args = tuple((a["name"], a["type"], bool(a.get("kwarg_only")), "default" in a, a.get("default")) for a in s["args"])
        rets = tuple(r["type"] for r in s["returns"])
        enums = {k: list(v) for k, v in (e.get("enum_args") or {}).items()}
        out.append(f"    {e['name']!r}: ({e['id']}, {flag_value(e.get('flags', []))}, {e['tier']}, {args!r}, "
                   f"{rets!r}, {enums!r}, {e.get('capability')!r}),")
    out.append("}\n")
    return "\n".join(out)


def gen_go(doc: dict) -> str:
    out = ["// SPDX-License-Identifier: Apache-2.0", "// Code generated by codegen/gen.py from opset/v1/opset.yaml. DO NOT EDIT.", "",
           "package opset", "", f"// Version is the opset version.\nconst Version = {doc['opset_version']}", "",
           "var table = []Op{"]
    for e in doc["ops"]:
        args = ", ".join(f"{{{json_str(a['name'])}, {json_str(a['type'])}, {str(bool(a.get('kwarg_only'))).lower()}}}"
                         for a in e["schema"]["args"])
        rets = ", ".join(json_str(r["type"]) for r in e["schema"]["returns"])
        enums = ", ".join(f"{json_str(k)}: {{{', '.join(json_str(x) for x in v)}}}"
                          for k, v in (e.get("enum_args") or {}).items())
        out.append(f"\t{{ID: {e['id']}, Name: {json_str(e['name'])}, Tier: {e['tier']}, Capability: "
                   f"{json_str(e.get('capability') or '')}, Flags: {flag_value(e.get('flags', []))}, "
                   f"Args: []Arg{{{args}}}, Returns: []string{{{rets}}}, Enums: map[string][]string{{{enums}}}}},")
    out += ["}", ""]
    return "\n".join(out)


def json_str(s: str) -> str:
    import json

    return json.dumps(s)


def gen_doc(doc: dict) -> str:
    out = ["<!-- Generated by codegen/gen.py from opset/v1/opset.yaml. Do not edit. -->", "",
           "# reFLOP opset v1", "",
           f"Pinned PyTorch: {doc['pinned_torch']}. {len(doc['ops'])} operators. Flags are explained in "
           "[PLAN.md §8.3](PLAN.md#83-security-flags).", ""]
    for tier, title in ((0, "Tier 0: Core ATen"), (1, "Tier 1: performance and training extensions"),
                        (2, "Tier 2: capability-gated")):
        rows = [e for e in doc["ops"] if e["tier"] == tier]
        out += [f"## {title} ({len(rows)})", "", "| id | operator | flags | validator | capability |",
                "|---:|---|---|---|---|"]
        for e in rows:
            out.append(f"| {e['id']} | `{e['name']}` | {' '.join(e.get('flags', [])) or ''} | "
                       f"{e.get('validator') or ''} | {e.get('capability') or ''} |")
        out.append("")
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    doc = load()
    files = {SERVER_OUT: gen_server(doc), CLIENT_OUT: gen_client(doc), DOC_OUT: gen_doc(doc), GO_OUT: gen_go(doc)}
    stale = []
    for path, text in files.items():
        if a.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(text)
    if stale:
        sys.exit("gen: out of date (run python codegen/gen.py): " + ", ".join(stale))
    print("gen: ok", file=sys.stderr)


if __name__ == "__main__":
    main()
