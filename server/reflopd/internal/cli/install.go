const (
	systemUser = "reflop"
	systemBin  = "/usr/local/lib/reflop/reflopd"
	systemUnit = "/etc/systemd/system/reflopd.service"
)

func installCmd() *cobra.Command {
	var system bool
	var listen []string
	cmd := &cobra.Command{
		Use:   "install --system",
		Short: "Level 1: install reflopd as a hardened system service (needs sudo once)",
		Long: `Level 1 moves reflopd into a dedicated system account. A hypothetical sandbox
escape then lands in an empty, unprivileged account instead of yours.

  sudo reflopd install --system [--listen 100.64.0.1:7460]

It creates the system user 'reflop' (no login shell, no home of its own),
/var/lib/reflop, /etc/reflop, a hardened systemd unit with cgroup delegation,
and installs the pinned runtime as that user. Manage it afterwards with
` + "`sudo reflopd --system <command>`" + `, e.g. sudo reflopd --system invite --name alice.`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			if !system {
				return exitWith(ExitUsage, errors.New("pass --system (level 0 needs no install: run `reflopd up`)"))
			}
			if os.Geteuid() != 0 {
				return exitWith(ExitUsage, errors.New("run with sudo: sudo reflopd install --system"))
			}
			return installSystem(cmd.OutOrStdout(), listen)
		},
	}
	cmd.Flags().BoolVar(&system, "system", false, "install the level 1 system service")
	cmd.Flags().StringSliceVar(&listen, "listen", nil, "address(es) for the system service to listen on")
	return cmd
}

func run(out io.Writer, name string, args ...string) error {
	c := exec.Command(name, args...)
	b, err := c.CombinedOutput()
	if err != nil {
		return fmt.Errorf("%s %s: %v: %s", name, strings.Join(args, " "), err, strings.TrimSpace(string(b)))
	}
	return nil
}

func installSystem(out io.Writer, listen []string) error {
	if _, err := user.Lookup(systemUser); err != nil {
		nologin := "/usr/sbin/nologin"
		if _, err := os.Stat(nologin); err != nil {
			nologin = "/sbin/nologin"
		}
		if err := run(out, "useradd", "--system", "--user-group", "--no-create-home", "--home-dir", paths.SystemRoot,
			"--shell", nologin, systemUser); err != nil {
			return err
		}
		fmt.Fprintf(out, "created system user %s\n", systemUser)
	}
	u, err := user.Lookup(systemUser)
	if err != nil {
		return err
	}
	uid, _ := strconv.Atoi(u.Uid)
	gid, _ := strconv.Atoi(u.Gid)
	exe, err := os.Executable()
	if err != nil {
		return err
	}
	exe, _ = filepath.EvalSymlinks(exe)
	if err := os.MkdirAll(filepath.Dir(systemBin), 0o755); err != nil {
		return err
	}
	b, err := os.ReadFile(exe)
	if err != nil {
		return err
	}
	if err := os.WriteFile(systemBin+".new", b, 0o755); err != nil {
		return err
	}
	if err := os.Rename(systemBin+".new", systemBin); err != nil {
		return err
	}
	for _, d := range []struct {
		path string
		mode os.FileMode
		own  bool
	}{{paths.SystemRoot, 0o750, true}, {"/etc/reflop", 0o750, true}} {
		if err := os.MkdirAll(d.path, d.mode); err != nil {
			return err
		}
		if d.own {
			os.Chown(d.path, uid, gid)
		}
	}
	inf := gpu.Detect()
	var devs []string
	for _, n := range gpu.DeviceNodes(inf.GPUs, inf.WSL) {
		devs = append(devs, "DeviceAllow="+n+" rw")
	}
	args := []string{systemBin, "serve"}
	for _, a := range listen {
		args = append(args, "--listen", a)
	}
	unit := fmt.Sprintf(`# Generated by reflopd install --system (PLAN.md §9.8).
[Unit]
Description=reFLOP daemon (reflopd, level 1)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=%[1]s
Group=%[1]s
Environment=REFLOP_SYSTEM=1 REFLOP_SCOPED=1
ExecStart=%[2]s
Restart=on-failure
RestartSec=3
RuntimeDirectory=reflop
RuntimeDirectoryMode=0750
UMask=0077
Delegate=yes
NoNewPrivileges=yes
ProtectSystem=strict
ProtectHome=yes
PrivateTmp=yes
ReadWritePaths=/var/lib/reflop /etc/reflop
CapabilityBoundingSet=
AmbientCapabilities=
RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6 AF_NETLINK
SystemCallArchitectures=native
SystemCallFilter=@system-service landlock_create_ruleset landlock_add_rule landlock_restrict_self seccomp
LockPersonality=yes
RestrictSUIDSGID=yes
RestrictRealtime=yes
ProtectClock=yes
ProtectHostname=yes
ProtectKernelModules=yes
ProtectKernelLogs=yes
ProtectKernelTunables=yes
DevicePolicy=closed
%[3]s
# MemoryDenyWriteExecute is not set: it is inherited by workers, and CUDA
# and PyTorch need writable+executable mappings (ADR-013).

[Install]
WantedBy=multi-user.target
`, systemUser, quoteArgs(args), strings.Join(devs, "\n"))
	if err := os.WriteFile(systemUnit, []byte(unit), 0o644); err != nil {
		return err
	}
	fmt.Fprintln(out, "installing the runtime as the reflop user (this downloads ~3 GB for CUDA)")
	c := exec.Command(systemBin, "runtime", "install")
	c.Env = []string{"REFLOP_SYSTEM=1", "PATH=/usr/sbin:/usr/bin:/sbin:/bin", "HOME=" + paths.SystemRoot}
	c.SysProcAttr = &syscall.SysProcAttr{Credential: &syscall.Credential{Uid: uint32(uid), Gid: uint32(gid)}}
	c.Stdout, c.Stderr = out, out
	if err := c.Run(); err != nil {
		return fmt.Errorf("runtime install: %w", err)
	}
	if err := run(out, "systemctl", "daemon-reload"); err != nil {
		return err
	}
	if err := run(out, "systemctl", "enable", "--now", "reflopd.service"); err != nil {
		return err
	}
	fmt.Fprintf(out, "level 1 service started. Manage it with: sudo reflopd --system status | invite --name <guest> | ...\n")
	fmt.Fprintln(out, "note: SSH pipe mode at level 1 needs a shell for the reflop user so sshd can run the forced command: sudo usermod -s /bin/sh reflop")
	return nil
}

func uninstallCmd() *cobra.Command {
	var system, purge bool
	cmd := &cobra.Command{
		Use:   "uninstall",
		Short: "Remove the service (level 0 user service, or level 1 with --system)",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			out := cmd.OutOrStdout()
			if system {
				if os.Geteuid() != 0 {
					return exitWith(ExitUsage, errors.New("run with sudo"))
				}
				_ = run(out, "systemctl", "disable", "--now", "reflopd.service")
				os.Remove(systemUnit)
				_ = run(out, "systemctl", "daemon-reload")
				os.Remove(systemBin)
				if purge {
					os.RemoveAll(paths.SystemRoot)
					os.RemoveAll("/etc/reflop")
					_ = run(out, "userdel", systemUser)
				}
				fmt.Fprintln(out, "level 1 service removed")
				return nil
			}
			if systemdUser() {
				exec.Command("systemctl", "--user", "disable", "--now", unitName).Run()
				home, _ := os.UserHomeDir()
				os.Remove(filepath.Join(home, ".config", "systemd", "user", unitName))
				exec.Command("systemctl", "--user", "daemon-reload").Run()
			}
			if purge {
				l, err := layout()
				if err == nil {
					for _, d := range []string{l.Config, l.State, l.Runtime, l.Scratch, l.Run} {
						os.RemoveAll(d)
					}
				}
			}
			fmt.Fprintln(out, "user service removed")
			return nil
		},
	}
	cmd.Flags().BoolVar(&system, "system", false, "remove the level 1 system service")
	cmd.Flags().BoolVar(&purge, "purge", false, "also delete identities, datasets, snapshots and runtimes")
	return cmd
}
